import turtle

t1: turtle = turtle
color: str = str(input("Color: "))
t1.begin_fill()
t1.color("red")
t1.fillcolor('red')
t1.forward(100)
t1.left(90)
t1.forward(100)
t1.left(90)
t1.forward(100)
t1.left(90)
t1.forward(100)
t1.end_fill()

t1.penup()
t1.goto(-200, 0)
t1.pendown()
t1.begin_fill()
t1.color(color)
t1.forward(100)
t1.left(90)
t1.forward(100)
t1.left(90)
t1.forward(100)
t1.left(90)
t1.forward(100)
t1.end_fill()
t1.done()
